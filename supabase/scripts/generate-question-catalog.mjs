import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build, createServer } from "vite";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const repositoryRoot = path.resolve(scriptDirectory, "../..");
const outputPath = path.join(
  repositoryRoot,
  "supabase/functions/_shared/generated/question-catalog.ts",
);

const server = await createServer({
  root: repositoryRoot,
  appType: "custom",
  logLevel: "silent",
  server: { middlewareMode: true },
});

try {
  const catalogModule = await server.ssrLoadModule(
    "/src/features/diagnostic/domain/catalog.ts",
  );
  const catalog = JSON.parse(JSON.stringify(catalogModule.interviewCatalog));
  const content = `// Generated from src/features/diagnostic/domain/catalog.ts.
// Run: node supabase/scripts/generate-question-catalog.mjs
// Do not edit this file manually.
export const GENERATED_INTERVIEW_CATALOG = ${JSON.stringify(catalog, null, 2)} as const;
`;
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, content, "utf8");
  process.stdout.write(
    `Generated ${catalog.questions.length} questions (${catalog.version}) at ${path.relative(repositoryRoot, outputPath)}\n`,
  );
} finally {
  await server.close();
}

await build({
  root: repositoryRoot,
  publicDir: false,
  configFile: false,
  logLevel: "silent",
  build: {
    target: "es2022",
    outDir: path.join(repositoryRoot, "supabase/functions/_shared/generated"),
    emptyOutDir: false,
    lib: {
      entry: path.join(repositoryRoot, "supabase/scripts/domain-runtime-entry.ts"),
      formats: ["es"],
      fileName: () => "domain-runtime.js",
    },
    rollupOptions: { external: ["zod"] },
  },
});
process.stdout.write("Generated canonical deterministic domain runtime\n");
